-- Q14 | Ticket médio por vendedor (sql/views.sql:219-236)
-- Q15 (sql/views.sql:238-256) e Q16 (sql/views.sql:258-277) eram versões
-- incrementais da mesma consulta; mantida a versão mais completa, com ranking.
SELECT
     ID_VENDEDOR,
     VENDEDOR,
     COUNT(*) AS TOTAL_PEDIDOS,
     SUM(FATURAMENTO) AS FATURAMENTO_TOTAL,
     ROUND(AVG(FATURAMENTO), 2) AS TICKET_MEDIO,
     RANK() OVER (ORDER BY SUM(FATURAMENTO) DESC) AS RANKING
FROM (
     SELECT
          V.ID_VENDEDOR,
          V.NOME AS VENDEDOR,
          P.ID_PEDIDO,
          SUM(I.QUANTIDADE * I.PRECO_UNITARIO) AS FATURAMENTO
     FROM VENDEDOR V
     INNER JOIN PEDIDO P
          ON P.ID_VENDEDOR = V.ID_VENDEDOR
     INNER JOIN ITENS_PEDIDO I
          ON I.ID_PEDIDO = P.ID_PEDIDO
     GROUP BY
          V.ID_VENDEDOR,
          V.NOME,
          P.ID_PEDIDO
) AS PEDIDOS
GROUP BY
     ID_VENDEDOR,
     VENDEDOR
ORDER BY FATURAMENTO_TOTAL DESC;



