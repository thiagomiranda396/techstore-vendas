-- Q12 | Ticket médio geral (sql/views.sql:197-205)
SELECT
     ROUND(AVG(VALOR_PEDIDO), 2) AS TICKET_MEDIO
FROM (
     SELECT
          ID_PEDIDO,
          SUM(QUANTIDADE * PRECO_UNITARIO) AS VALOR_PEDIDO
     FROM ITENS_PEDIDO
     GROUP BY ID_PEDIDO
) AS PEDIDOS;



