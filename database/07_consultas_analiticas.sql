-- Q01 | Produtos por categoria (sql/views.sql:43-50)
-- Correção: GROUP BY ambíguo; LEFT JOIN para exibir categorias sem produto.
SELECT
     C.ID_CATEGORIA,
     C.NOME AS CATEGORIA,
     COUNT(P.ID_PRODUTO) AS TOTAL_PRODUTOS
FROM CATEGORIA C
LEFT JOIN PRODUTO P
     ON P.ID_CATEGORIA = C.ID_CATEGORIA
GROUP BY
     C.ID_CATEGORIA,
     C.NOME
ORDER BY TOTAL_PRODUTOS DESC;



-- Q02 | Produtos e preço médio por categoria (sql/views.sql:52-61)
SELECT
     C.ID_CATEGORIA,
     C.NOME AS CATEGORIA,
     COUNT(*) AS TOTAL_PRODUTOS,
     ROUND(AVG(P.PRECO), 2) AS PRECO_MEDIO
FROM PRODUTO P
INNER JOIN CATEGORIA C
     ON P.ID_CATEGORIA = C.ID_CATEGORIA
GROUP BY
     C.ID_CATEGORIA,
     C.NOME
ORDER BY PRECO_MEDIO DESC;



