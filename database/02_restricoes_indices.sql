-- -----------------------------------------------------------------------------
-- Novas restrições (Fase 3)
-- -----------------------------------------------------------------------------

-- Um produto aparece no máximo uma vez por pedido.
ALTER TABLE ITENS_PEDIDO
ADD CONSTRAINT UQ_ITENS_PEDIDO_PEDIDO_PRODUTO
UNIQUE(ID_PEDIDO, ID_PRODUTO);



ALTER TABLE CLIENTE
ADD CONSTRAINT CK_CLIENTE_CPF_FORMATO
CHECK(CPF ~ '^[0-9]{11}$');



ALTER TABLE ENDERECO
ADD CONSTRAINT CK_ENDERECO_CEP_FORMATO
CHECK(CEP ~ '^[0-9]{8}$');



ALTER TABLE ENDERECO
ADD CONSTRAINT CK_ENDERECO_UF_FORMATO
CHECK(UF ~ '^[A-Z]{2}$');



ALTER TABLE PRODUTO
ADD CONSTRAINT CK_PRODUTO_CUSTO
CHECK(CUSTO IS NULL OR CUSTO > 0);



ALTER TABLE PRODUTO
ADD CONSTRAINT CK_PRODUTO_CUSTO_ORIGEM
CHECK(CUSTO_ORIGEM IS NULL OR CUSTO_ORIGEM IN('REAL', 'SINTETICO'));



-- Custo, origem e fonte: todos preenchidos ou todos vazios.
ALTER TABLE PRODUTO
ADD CONSTRAINT CK_PRODUTO_CUSTO_CONSISTENCIA
CHECK(
    (CUSTO IS NULL AND CUSTO_ORIGEM IS NULL AND CUSTO_FONTE IS NULL)
    OR
    (CUSTO IS NOT NULL AND CUSTO_ORIGEM IS NOT NULL AND CUSTO_FONTE IS NOT NULL)
);



ALTER TABLE ITENS_PEDIDO
ADD CONSTRAINT CK_ITENS_PEDIDO_CUSTO
CHECK(CUSTO_UNITARIO IS NULL OR CUSTO_UNITARIO > 0);



-- A regra "pedido não pode ser anterior ao cadastro do cliente" envolve duas
-- tabelas e não cabe em CHECK; ela é validada em 08_verificacoes_qualidade.sql.



-- -----------------------------------------------------------------------------
-- Índices nas chaves estrangeiras (o PostgreSQL não os cria automaticamente)
-- ITENS_PEDIDO(ID_PEDIDO) já é coberto por UQ_ITENS_PEDIDO_PEDIDO_PRODUTO,
-- cuja primeira coluna é ID_PEDIDO; um índice separado seria redundante.
-- -----------------------------------------------------------------------------

CREATE INDEX IX_ENDERECO_ID_CLIENTE ON ENDERECO(ID_CLIENTE);

CREATE INDEX IX_TELEFONE_ID_CLIENTE ON TELEFONE(ID_CLIENTE);

CREATE INDEX IX_PRODUTO_ID_CATEGORIA ON PRODUTO(ID_CATEGORIA);

CREATE INDEX IX_PEDIDO_ID_CLIENTE ON PEDIDO(ID_CLIENTE);

CREATE INDEX IX_PEDIDO_ID_VENDEDOR ON PEDIDO(ID_VENDEDOR);

CREATE INDEX IX_ITENS_PEDIDO_ID_PRODUTO ON ITENS_PEDIDO(ID_PRODUTO);
